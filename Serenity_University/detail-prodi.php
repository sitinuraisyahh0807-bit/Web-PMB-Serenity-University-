        function tampilkanProdi() {
            let targetId = window.location.hash.substring(1); 
            if (!targetId) targetId = "teknik-informatika"; // Default jika tidak ada # di URL

            const allProdi = document.querySelectorAll('.prodi-content');
            allProdi.forEach(prodi => {
                if (prodi.id === targetId) {
                    prodi.style.setProperty('display', 'block', 'important');
                } else {
                    prodi.style.setProperty('display', 'none', 'important');
                }
            });
            window.scrollTo(0, 0); // Gulir ke atas saat ganti prodi
        }

        document.addEventListener("DOMContentLoaded", tampilkanProdi);
        window.addEventListener("hashchange", tampilkanProdi);
    </script>
