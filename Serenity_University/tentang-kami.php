    <script>

        const facilitySlider =
            document.getElementById("facilitySlider");

        const facilityPrev =
            document.getElementById("facilityPrev");

        const facilityNext =
            document.getElementById("facilityNext");


        function geserFasilitas(arah) {

            const card =
                facilitySlider.querySelector(".facility-card");

            const gap = 18;

            const jarak =
                card ? card.offsetWidth + gap : 250;


            facilitySlider.scrollBy({

                left: arah * jarak * 2,

                behavior: "smooth"

            });

        }


        facilityPrev.addEventListener(
            "click",
            () => geserFasilitas(-1)
        );


        facilityNext.addEventListener(
            "click",
            () => geserFasilitas(1)
        );


        /* Mencegah slider digeser horizontal
           menggunakan mouse/touchpad */

        facilitySlider.addEventListener(
            "wheel",
            function (event) {

                if (
                    Math.abs(event.deltaX) >
                    Math.abs(event.deltaY)
                ) {

                    event.preventDefault();

                }

            },
            { passive: false }
        );

    </script>

